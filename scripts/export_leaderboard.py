"""Generate website data from the current public score release (no model requests)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASK_KEYS = dict(zip(
    ("Format", "Transform", "Distance", "Bearing", "Interpolation", "Area", "BBox", "Geometry", "RelPure",
     "Place", "Disambiguation", "RelApplied", "Proximity", "Route", "Boundary", "Spatial", "Terrain"),
    ("format_conversion", "coordinate_transformation", "distance_calculation", "bearing_computation",
     "coordinate_interpolation", "area_perimeter", "bounding_box", "route_geometry", "relative_position_gps",
     "place_association", "name_disambiguation", "relative_position_applied", "proximity", "route_analysis",
     "boundary_analysis", "spatial_patterns", "terrain_classification")))


def main():
    scores = json.loads((ROOT / "results/current/scores.json").read_text())
    config = json.loads((ROOT / "leaderboard/config.json").read_text())
    data = {k: config[k] for k in ("categories", "taskMeta", "providerColors")}
    data["meta"] = {"name": "GPSBench", "description": "GPS reasoning in large language models",
                    "totalSamples": 58614, "totalTasks": 17, "testSamples": 17342,
                    "scoringVersion": scores["version"], "tracks": {
                        "pure_gps": {"name": "Pure GPS", "tasks": 9},
                        "applied": {"name": "Applied", "tasks": 8}}}
    data["models"] = []
    for model in scores["models"]:
        key = "mistral-small" if model["name"] == "Mistral-Small-24B" else model["name"].lower()
        data["models"].append({**config["models"][key], "overall": model["overall"],
                               "total": 17342, "pure_gps": {"score": model["pure"], "total": 9182},
                               "applied": {"score": model["applied"], "total": 8160},
                               "tasks": {TASK_KEYS[t]: v for t, v in model["scores"].items()}})
    (ROOT / "leaderboard/data.js").write_text(
        "// Generated by scripts/export_leaderboard.py; edit config.json for descriptions.\n"
        + "const BENCHMARK_DATA = " + json.dumps(data, indent=2, allow_nan=False) + ";\n")
    print(f"Exported {len(data['models'])} models and {len(data['taskMeta'])} tasks")


if __name__ == "__main__":
    main()
